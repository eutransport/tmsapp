def _inlezen(apps, schema_editor):
    # Binnen de migratie importeren: bij het laden van de migratiemodule zijn
    # de apps nog niet klaar. Het echte model, niet het historische, omdat de
    # inleesroutine daar instanties van teruggeeft.
    from apps.tolling.models import TollingEvent
    from apps.tolling.services import lees_bestand

    for naam, factuurdatum, inhoud in AFREKENINGEN:
        voorbereiding = lees_bestand(inhoud.strip().encode('utf-8'))
        if voorbereiding.missing:
            raise RuntimeError(
                f'{naam}: kolommen ontbreken: {sorted(voorbereiding.missing)}')
        if not voorbereiding.events:
            raise RuntimeError(f'{naam}: geen regels gevonden')

        gefactureerd_op = timezone.make_aware(
            timezone.datetime.combine(factuurdatum, timezone.datetime.min.time()),
            timezone.get_current_timezone(),
        )

        bestaand = set(
            TollingEvent.objects
            .filter(license_plate_normalized__in={e.license_plate_normalized
                                                  for e in voorbereiding.events})
            .values_list('license_plate_normalized', 'start_at', 'amount', 'obu')
        )
        nieuw = []
        for event in voorbereiding.events:
            # Het boekingsnummer hoort bij de sleutel: Toll Collect boekt
            # eenzelfde passage soms twee keer, via de OBU en via de app.
            sleutel = (event.license_plate_normalized, event.start_at,
                       event.amount, event.obu)
            if sleutel in bestaand:
                continue
            bestaand.add(sleutel)
            event.invoiced_at = gefactureerd_op
            nieuw.append(event)

        if nieuw:
            TollingEvent.objects.bulk_create(nieuw, batch_size=200)
        print(f'  {naam}: {len(nieuw)} van {len(voorbereiding.events)} regels toegevoegd')


